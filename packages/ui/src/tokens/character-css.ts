/**
 * The characters as a stylesheet (design language section 19): `data-strata-character="studio"` on the root or on a
 * scope turns the custom properties of that subtree into the character's, so the CSS, Relief, Objects and Instrument
 * levels all follow it from the same markup. Premium is the default and its numbers are the runtime's own, so the
 * default needs no attribute; its block exists so that a `premium` scope inside a `studio` one restores them.
 *
 * - **What it declares:** the tokens that any non-default character sets, and premium's material tokens (one list, so
 *   that every block restates all of them: a token a character does not set takes premium's value, or none where premium
 *   has none). Only tokens a
 *   character may set are there; the same rules as `applyCharacter` decide.
 * - **Scope or application:** `studio.*` and `environment.*` are the application's, so they sit on `:root` only;
 *   a scoped character's values for them are not declared (they are reported by `createStrataTheme`).
 * - **Themes:** a token with per-theme values (the wall plate's material) is declared for each theme, on the scope and on
 *   a theme scope inside it, and for the system's dark scheme where the root has no theme of its own.
 * - **Cascade:** in the `strata.theme` layer, above the defaults and below the components, like a theme's own sheet.
 */
import { applyCharacter, characterNames, characterOf, defaultCharacter } from "./character.ts";
import { cssVariable, layerOrder, literal } from "./css.ts";
import { finishGradient, finishRecipes } from "./finish.ts";
import { flatten, themesOf, valueOf, type Token } from "./model.ts";
import { strataSource } from "./source.ts";

/** The application-only tokens (design language section 19): declared on the root. */
const applicationOnly = /^(environment|studio)\./;
/** The tokens of the materials, which every block restates whole: a role may name any preset of any character. */
const materialLayer = /^(instrument\.|material\.)/;

const lines = (declarations: string[], indent: string) => declarations.map(line => `${indent}  ${line}`).join("\n");
const rule = (selector: string, declarations: string[], indent = "  ") => `${indent}${selector} {\n${lines(declarations, indent)}\n${indent}}`;

/** The character's token layer by path (a character that is not built in has none). */
function tokensOf(name: string): Map<string, Token> {
  const character = characterOf(name);
  return new Map("tokens" in character ? flatten(character.tokens).map(token => [token.path, token]) : []);
}

/**
 * The stylesheet for the characters: a block per built-in character, in the `strata.theme` layer. Generated by the build
 * into `tokens.css` (and so `strata.css`); the page needs nothing else to switch character.
 */
export function charactersToCss(names: readonly string[] = characterNames): string {
  const layers = new Map(names.map(name => [name, tokensOf(name)]));
  const base = layers.get(defaultCharacter) ?? new Map<string, Token>();
  const themes = Object.keys(themesOf(strataSource));
  // The paths any non-default character sets, in the order they first appear; tokens a character may not set are left out.
  const paths: string[] = [...base.keys()].filter(path => materialLayer.test(path));
  for (const name of names) {
    if (name === defaultCharacter) continue;
    const applied = new Set(applyCharacter(strataSource, name).applied);
    for (const path of layers.get(name)!.keys()) if (applied.has(path) && !paths.includes(path)) paths.push(path);
  }
  const tokenFor = (name: string, path: string) => layers.get(name)!.get(path) ?? base.get(path);
  const declare = (name: string, path: string, theme?: string) => {
    const token = tokenFor(name, path), variable = cssVariable(path);
    if (!token) return `${variable}: initial;`;
    return `${variable}: ${literal(token, theme === undefined ? token.$value : valueOf(token, { theme }))};`;
  };
  const parts = [layerOrder, "@layer strata.theme {"];
  for (const name of names) {
    const scope = `[data-strata-character="${name}"]`, inner = `${scope} [data-strata-theme]`;
    const own = (path: string) => !applicationOnly.test(path);
    const themed = (path: string) => Object.keys(tokenFor(name, path)?.meta.themes ?? {}).length > 0;
    parts.push(`  /* ${name} */`);
    parts.push(rule(`${scope}, ${inner}`, paths.filter(path => own(path) && !themed(path)).map(path => declare(name, path))));
    parts.push(rule(`:root${scope}`, paths.filter(path => !own(path)).map(path => declare(name, path))));
    const themedPaths = paths.filter(path => own(path) && themed(path));
    if (themedPaths.length) {
      // Light first (a scope under no theme), then the system's dark scheme where no theme is named, then each named theme:
      // on the scope itself, on a theme scope inside it, and on the scope when a theme scope encloses it.
      parts.push(rule(`${scope}`, themedPaths.map(path => declare(name, path, "light"))));
      parts.push("  @media (prefers-color-scheme: dark) {", rule(`:root:not([data-strata-theme])${scope}, :root:not([data-strata-theme]) ${scope}`, themedPaths.map(path => declare(name, path, "dark")), "    "), "  }");
      for (const theme of themes) {
        const named = `[data-strata-theme="${theme}"]`;
        parts.push(rule(`${scope}${named}, ${scope} ${named}, ${named} ${scope}`, themedPaths.map(path => declare(name, path, theme))));
      }
    }
    // The CSS-only finish of a material, and of each role, from the character's own recipe (section 4).
    const recipes = finishRecipes(applyCharacter(strataSource, name).source);
    const finishes = Object.keys(recipes).filter(preset => paths.some(path => path.startsWith(`material.presets.${preset}.`)));
    const roles = paths.filter(path => path.startsWith("material.roles.")).map(path => path.split(".")[2]!);
    const declarations = [
      ...finishes.map(preset => `--strata-finish-${preset}: ${finishGradient(recipes[preset]!)};`),
      ...roles.map(role => `${cssVariable(`finish.role.${role}`)}: var(--strata-finish-${String(valueOf(tokenFor(name, `material.roles.${role}`) as Token, { theme: "light" }))});`),
    ];
    if (declarations.length) parts.push(rule(scope, declarations));
  }
  parts.push("}");
  return `${parts.join("\n")}\n`;
}
